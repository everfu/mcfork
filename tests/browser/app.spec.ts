test('production build works from a static subdirectory without a backend or Token', async ({ page }) => {
  const apiRequests: string[] = [];
  page.on('request', request => { if (request.url().includes('/api/')) apiRequests.push(request.url()); });
  await page.route('https://static.mcfork.test/**', async route => {
    const path = new URL(route.request().url()).pathname.replace(/^\/preview\//, '') || 'index.html';
    const types: Record<string, string> = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.png': 'image/png', '.gif': 'image/gif' };
    try { await route.fulfill({ body: await readFile(resolve('dist', path)), contentType: types[extname(path)] ?? 'application/octet-stream' }); }
    catch { await route.fulfill({ status: 404, body: 'Missing test asset' }); }
  });
  await page.goto('https://static.mcfork.test/preview/');
  await expect(page.locator('.variant')).toHaveCount(2);
  await expect(page.locator('.district-select button')).toBeEnabled();
  await expect(page.getByRole('button', { name: '演示试算', exact: true })).toBeVisible();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出对比小票', exact: true }).click();
  expect((await download).suggestedFilename()).toContain('演示');
  expect(apiRequests).toEqual([]);
});
