test('live area selection auto-loads stores and discards a slow previous query', async ({ page }) => {
  const snapshot = JSON.parse(await readFile('shared/snapshot.json', 'utf8'));
  const searches: { city: string; keyword: string }[] = [];
  let releaseOld!: () => void;
  const oldResult = new Promise<void>(resolve => { releaseOld = resolve; });
  await page.unroute('**/api/config');
  await page.route('**/api/config', route => route.fulfill({ json: { liveAvailable: true } }));
  await page.route('**/api/menu?**', route => route.fulfill({ json: { mode: 'live', meals: snapshot.meals } }));
  await page.route('**/api/stores', async route => {
    const input = route.request().postDataJSON(); searches.push(input);
    if (input.keyword === '王府井') await oldResult;
    await route.fulfill({ json: { mode: 'live', stores: input.city === '杭州' ? snapshot.stores : [{ id: input.keyword, name: `麦当劳${input.keyword}测试餐厅`, address: `${input.city}${input.keyword}测试地址` }], queriedAt: new Date().toISOString() } }).catch(() => {});
  });
  await page.goto('/');
  await expect(page.getByRole('button', { name: '官方实时', exact: true })).toBeEnabled();
  await page.locator('.city-select button').click();
  await page.getByRole('option', { name: '北京', exact: true }).click();
  await page.locator('.district-select button').click();
  await page.getByRole('option', { name: '王府井', exact: true }).click();
  await expect(page.locator('.location-feedback')).toContainText('正在查询北京');
  await expect.poll(() => searches.some(input => input.city === '北京' && input.keyword === '王府井')).toBe(true);
  await page.locator('.district-select button').click();
  await page.getByRole('option', { name: '西单', exact: true }).click();
  await expect(page.locator('.location-feedback')).toContainText('北京 · 西单 · 已加载 1 家门店');
  releaseOld();
  await page.getByRole('button', { name: '选择真实门店' }).click();
  await expect(page.getByRole('dialog', { name: '选一家真实门店' }).locator('.store-option')).toContainText('西单测试餐厅');
  await expect(page.getByRole('dialog', { name: '选一家真实门店' })).not.toContainText('王府井测试餐厅');
  await page.getByRole('dialog', { name: '选一家真实门店' }).locator('.store-option').click();
  await expect(page.locator('.store-address')).toContainText('西单测试餐厅');
  expect(searches.filter(input => input.keyword === '西单')).toHaveLength(1);
});
